#!/usr/bin/env python3
"""Build ``demo/lesson_01/lesson.mp4`` — a stand-in Zoom recording made from the demo keyframes.

The real demo lesson is ~35 minutes long; the video only needs to *exist* so the pipeline can run ffprobe,
extract an audio track and pick keyframes from it. By default the timeline is compressed to ~90 seconds:
every frame from ``frames/frames.json`` is shown for its share of the real lesson, so scene detection yields
the same 12 frames in the same order. ``--realtime`` keeps the true timestamps (≈34 minutes of mostly
static video — still small, because H.264 compresses static slides very well).

The audio track is a quiet synthetic tone (ffmpeg ``lavfi`` ``sine``), not speech: the mock STT provider
returns ``transcript.json`` regardless of the audio content, and the mock LLM returns ``analysis.json``
regardless of the frames. Real providers would obviously produce nonsense for this file.

Usage::

    python demo/build_demo_media.py                # ~90 s, H.264 yuv420p + AAC, < 4 MB
    python demo/build_demo_media.py --realtime     # true timestamps (~34 min)
    python demo/build_demo_media.py --out /tmp/x.mp4 --duration 60

Requires ``ffmpeg`` / ``ffprobe`` on PATH (or ``FFMPEG_BIN`` / ``FFPROBE_BIN``). Frames are generated by
``demo/make_frames.py`` if missing.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DEMO_DIR = Path(__file__).resolve().parent
LESSON_DIR = DEMO_DIR / "lesson_01"
FRAMES_DIR = LESSON_DIR / "frames"
DEFAULT_OUT = LESSON_DIR / "lesson.mp4"

DEFAULT_DURATION_SEC = 90.0
LESSON_END_SEC = 2100.0  # real length of the demo lesson (≈35 min)
FPS = 10
TONE_HZ = 220
TONE_VOLUME = 0.03  # -30 dB: present but quiet
MAX_BYTES = 4 * 1024 * 1024
# Slide changes are rendered as a short ramp: the current slide fades into a dimmed copy of the NEXT slide over
# TRANSITION_STEPS frames, then jumps to full brightness. ffmpeg's scene score is
# ``min(mafd, |mafd - prev_mafd|) / 100`` (mean absolute frame difference in 8-bit units), so every ramp step
# stays below the 0.30 threshold while the final jump (≈ (1 - TRANSITION_DIM) × slide luma) exceeds it. The
# pipeline therefore captures exactly one scene frame per slide — the real slide, at full brightness — even
# between two white slides whose direct difference would be far below the threshold.
TRANSITION_STEPS = 4
TRANSITION_DIM = 0.65
TRANSITION_SEC = TRANSITION_STEPS / FPS


class BuildError(RuntimeError):
    """ffmpeg/ffprobe failed or produced an unexpected result."""


def _bin(name: str) -> str:
    return os.environ.get(f"{name.upper()}_BIN") or shutil.which(name) or name


def load_frames(frames_dir: Path = FRAMES_DIR) -> list[dict]:
    """Return ``frames.json`` entries sorted by index; generate the frames when missing."""
    meta_path = frames_dir / "frames.json"
    if not meta_path.is_file():
        sys.path.insert(0, str(DEMO_DIR))
        from make_frames import build as build_frames  # noqa: PLC0415

        build_frames(frames_dir)
    frames = json.loads(meta_path.read_text(encoding="utf-8"))
    frames.sort(key=lambda f: f["index"])
    for f in frames:
        if not (frames_dir / f"{f['index']:04d}.jpg").is_file():
            raise BuildError(f"frame file missing: {frames_dir / f'{f["index"]:04d}.jpg'}")
    return frames


def frame_durations(frames: list[dict], *, total_sec: float | None, lesson_end: float = LESSON_END_SEC) -> list[float]:
    """Seconds each frame stays on screen.

    ``total_sec=None`` → real durations (next timestamp − this timestamp; the last frame runs to
    ``lesson_end``). Otherwise the same proportions are scaled so the sum equals ``total_sec``, with a floor of
    1.5 s per frame so scene detection and interval sampling see every slide.
    """
    stamps = [float(f["timestamp_sec"]) for f in frames]
    # The first slide covers the video from t=0, so that in realtime mode slide i+1 starts exactly at its real
    # timestamp (the frame timestamps the pipeline extracts then match frames.json / analysis.json).
    starts = [0.0, *stamps[1:]]
    real = [max(0.5, (starts[i + 1] if i + 1 < len(starts) else lesson_end) - starts[i]) for i in range(len(starts))]
    if total_sec is None:
        return real
    scale = total_sec / sum(real)
    scaled = [max(1.5, d * scale) for d in real]
    # re-normalise after applying the floor so the total is exact
    fix = total_sec / sum(scaled)
    return [round(d * fix, 3) for d in scaled]


def make_transition_frames(frames: list[dict], frames_dir: Path, tmp_dir: Path) -> list[list[Path]]:
    """For every slide i write the ramp frames leading into slide i+1; returns one list of paths per slide."""
    from PIL import Image, ImageEnhance  # noqa: PLC0415

    out: list[list[Path]] = []
    for i, f in enumerate(frames):
        if i + 1 >= len(frames):
            out.append([])
            continue
        src = frames_dir / f"{f['index']:04d}.jpg"
        nxt = frames_dir / f"{frames[i + 1]['index']:04d}.jpg"
        with Image.open(src) as a_im, Image.open(nxt) as b_im:
            a = a_im.convert("RGB")
            target = ImageEnhance.Brightness(b_im.convert("RGB")).enhance(TRANSITION_DIM)
            steps: list[Path] = []
            for k in range(1, TRANSITION_STEPS + 1):
                dst = tmp_dir / f"ramp_{f['index']:04d}_{k}.jpg"
                Image.blend(a, target, k / TRANSITION_STEPS).save(dst, format="JPEG", quality=85)
                steps.append(dst)
        out.append(steps)
    return out


def _concat_path(path: Path) -> str:
    return path.resolve().as_posix().replace("'", r"'\''")


def write_concat_list(
    frames: list[dict],
    durations: list[float],
    path: Path,
    frames_dir: Path = FRAMES_DIR,
    transitions: list[list[Path]] | None = None,
) -> None:
    """Write an ffmpeg concat-demuxer list: slide, ramp frames, next slide, … (last file repeated, per ffmpeg)."""
    lines = ["ffconcat version 1.0"]
    step = 1.0 / FPS
    for i, (f, d) in enumerate(zip(frames, durations, strict=True)):
        ramp = transitions[i] if transitions else []
        if d <= len(ramp) * step + 1.0:
            ramp = []
        lines.append(f"file '{_concat_path(frames_dir / f'{f["index"]:04d}.jpg')}'")
        lines.append(f"duration {d - len(ramp) * step:.3f}")
        for r in ramp:
            lines.append(f"file '{_concat_path(r)}'")
            lines.append(f"duration {step:.3f}")
    lines.append(f"file '{_concat_path(frames_dir / f'{frames[-1]["index"]:04d}.jpg')}'")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_ffmpeg(concat_list: Path, out: Path, *, total_sec: float, realtime: bool) -> None:
    audio_bitrate = "16k" if realtime else "48k"
    crf = "30" if realtime else "26"
    cmd = [
        _bin("ffmpeg"),
        "-y",
        "-nostdin",
        "-loglevel",
        "error",
        "-f",
        "concat",
        "-safe",
        "0",
        "-i",
        str(concat_list),
        "-f",
        "lavfi",
        "-i",
        f"sine=frequency={TONE_HZ}:sample_rate=16000",
        "-filter_complex",
        f"[1:a]volume={TONE_VOLUME},tremolo=f=0.5:d=0.6[a]",
        "-map",
        "0:v",
        "-map",
        "[a]",
        "-r",
        str(FPS),
        "-c:v",
        "libx264",
        "-preset",
        "medium",
        "-tune",
        "stillimage",
        "-crf",
        crf,
        "-pix_fmt",
        "yuv420p",
        "-vf",
        "scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2",
        "-c:a",
        "aac",
        "-b:a",
        audio_bitrate,
        "-ac",
        "1",
        "-t",
        f"{total_sec:.3f}",
        "-movflags",
        "+faststart",
        str(out),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise BuildError(f"ffmpeg failed ({proc.returncode}): {proc.stderr.strip()[-800:]}")


def probe_duration(path: Path) -> float:
    """Container duration in seconds via ffprobe."""
    proc = subprocess.run(
        [_bin("ffprobe"), "-v", "error", "-show_entries", "format=duration", "-of", "json", str(path)],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise BuildError(f"ffprobe failed: {proc.stderr.strip()[-400:]}")
    return float(json.loads(proc.stdout)["format"]["duration"])


def build(
    out: Path = DEFAULT_OUT,
    *,
    realtime: bool = False,
    duration_sec: float = DEFAULT_DURATION_SEC,
    frames_dir: Path = FRAMES_DIR,
    quiet: bool = False,
) -> Path:
    """Render the demo video to ``out`` and return its path."""
    frames = load_frames(frames_dir)
    durations = frame_durations(frames, total_sec=None if realtime else duration_sec)
    total = sum(durations)
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="lessonlens-demo-") as tmp:
        concat_list = Path(tmp) / "frames.ffconcat"
        transitions = make_transition_frames(frames, frames_dir, Path(tmp))
        write_concat_list(frames, durations, concat_list, frames_dir, transitions)
        run_ffmpeg(concat_list, out, total_sec=total, realtime=realtime)
    size = out.stat().st_size
    probed = probe_duration(out)
    if not quiet:
        mode = "realtime" if realtime else f"compressed to {duration_sec:.0f}s"
        print(f"{out}: {probed:.1f}s, {size / 1024 / 1024:.2f} MB, {len(frames)} frames ({mode})")
        if not realtime and size > MAX_BYTES:
            print(f"warning: file is larger than {MAX_BYTES // 1024 // 1024} MB", file=sys.stderr)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the demo lesson video from the demo keyframes.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output mp4 (default: demo/lesson_01/lesson.mp4)")
    parser.add_argument(
        "--realtime", action="store_true", help="use the real lesson timestamps (~34 min) instead of ~90 s"
    )
    parser.add_argument(
        "--duration",
        type=float,
        default=DEFAULT_DURATION_SEC,
        help="target length in seconds (ignored with --realtime)",
    )
    parser.add_argument("--frames-dir", type=Path, default=FRAMES_DIR, help="directory with NNNN.jpg + frames.json")
    args = parser.parse_args(argv)
    try:
        build(args.out, realtime=args.realtime, duration_sec=args.duration, frames_dir=args.frames_dir)
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
