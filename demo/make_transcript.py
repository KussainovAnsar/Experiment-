def is_kazakh(text: str) -> bool:
    return any(ch in text.lower() for ch in KAZAKH_MARKERS)


def fmt(sec: float) -> str:
    m, s = divmod(int(sec), 60)
    return f"{m:02d}:{s:02d}"


def build_segments(rng: random.Random) -> list[dict]:
    """Lay the lines out on the timeline; returns transcript segments."""
    segments: list[dict] = []
    clock = 0.0
    for section in SECTIONS:
        if section.start < clock:
            raise SystemExit(f"section «{section.title}» starts at {section.start}s but the clock is at {clock:.1f}s")
        clock = section.start
        for line in section.lines:
            if line.at is not None:
                if line.at < clock:
                    raise SystemExit(f"line «{line.text[:40]}» anchored at {line.at}s but the clock is at {clock:.1f}s")
                clock = line.at
            duration = max(MIN_SEGMENT, len(line.text) / CHARS_PER_SEC + rng.uniform(0.2, 0.7))
            start = round(clock, 2)
            end = round(clock + duration, 2)
            lo, hi = (0.80, 0.90) if is_kazakh(line.text) else (0.86, 0.98)
            segments.append(
                {
                    "start": start,
                    "end": end,
                    "speaker": line.speaker,
                    "text": line.text,
                    "confidence": round(rng.uniform(lo, hi), 2),
                }
            )
            clock = end + rng.uniform(0.4, 1.3) + line.pause_after
    if clock > LESSON_END:
        raise SystemExit(f"dialogue runs to {clock:.0f}s, beyond the {LESSON_END:.0f}s lesson")
    return segments


def write_transcript(segments: list[dict]) -> Path:
    data = {
        "provider": "mock",
        "language": "ru",
        "speaker_map": {"SPEAKER_00": "teacher", "SPEAKER_01": "student"},
        "segments": segments,
    }
    path = LESSON_DIR / "transcript.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


