def write_script(segments: list[dict]) -> Path:
    lines: list[str] = [SCRIPT_INTRO]
    idx = 0
    for section in SECTIONS:
        lines.append(f"\n### [{fmt(section.start)}] {section.title}\n")
        lines.append(f"*На экране:* {section.screen}\n")
        for _ in section.lines:
            seg = segments[idx]
            idx += 1
            who = "Учитель" if seg["speaker"] == T else "Ученик"
            lines.append(f"- **[{fmt(seg['start'])}] {who}:** {seg['text']}")
    lines.append("")
    path = LESSON_DIR / "script.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


