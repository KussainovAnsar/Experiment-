    n_student = sum(1 for s in segments if s["speaker"] == S)
    print(f"{t_path}: {len(segments)} segments, {n_student} student turns, last end {segments[-1]['end']:.1f}s")
    print(f"{s_path} written")
    anchors = [s for s in segments if s["start"] in (860.0, 1145.0)]
    for a in anchors:
        print(f"  anchor {fmt(a['start'])}: {a['text']}")
    return 0


